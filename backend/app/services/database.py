from __future__ import annotations
from typing import Any
from sqlalchemy import func, select
from sqlalchemy.orm import Session
from ..errors import ResourceNotFound
from ..schemas import *


class DatabaseWellService:
    """Adapter around the existing NWIS database repository/models.

    This adapter performs persistence access only. Domain calculations remain in
    the existing repository/module services.
    """
    def __init__(self, session: Session):
        from database.models import Well, WellTrajectory
        from database.repositories import WellRepository
        self.session = session
        self.Well = Well
        self.WellTrajectory = WellTrajectory
        self.repo = WellRepository(session)

    def list_wells(self, limit, offset):
        stmt = select(self.Well).order_by(self.Well.well_id).offset(offset).limit(limit)
        items = self.session.scalars(stmt).all()
        total = self.session.scalar(select(func.count()).select_from(self.Well)) or 0
        return [WellResponse.model_validate(x) for x in items], int(total)

    def get_well(self, well_id):
        obj = self.repo.get_well(well_id)
        if obj is None:
            raise ResourceNotFound(f"Well '{well_id}' was not found")
        return WellResponse.model_validate(obj)

    def nearby_wells(self, well_id, radius_km, limit, offset):
        # Existing repository performs the PostGIS spatial calculation.
        items = list(self.repo.get_nearby_wells(well_id, radius_km, limit=limit + offset))
        source = self.repo.get_well(well_id)
        if source is None:
            raise ResourceNotFound(f"Well '{well_id}' was not found")
        # Use the repository's richer metadata method so distance/formation/event
        # data are generated by the database module rather than duplicated here.
        rich = self.repo.get_similar_wells_metadata(well_id, radius_km=radius_km, limit=limit + offset)
        out = [NearbyWellResponse.model_validate(x) for x in rich[offset:offset+limit]]
        return out, len(rich)

    def events(self, well_id, event_type, limit, offset):
        self.get_well(well_id)
        all_items = list(self.repo.get_well_events(well_id, event_type=event_type, limit=limit + offset))
        return [DrillingEventResponse.model_validate(x) for x in all_items[offset:offset+limit]], len(all_items)

    def monitoring(self, well_id):
        well = self.repo.get_well(well_id)
        if well is None:
            raise ResourceNotFound(f"Well '{well_id}' was not found")
        params = list(self.repo.get_drilling_parameters(well_id, limit=1))
        from ..schemas import MonitoringSnapshotResponse
        if not params:
            return MonitoringSnapshotResponse(well_id=well_id)
        p = params[-1]
        formations = list(self.repo.get_formation_data(well_id, float(p.measured_depth_m) if p.measured_depth_m is not None else None))
        return MonitoringSnapshotResponse(
            well_id=well_id, timestamp=p.recorded_at,
            depth=float(p.measured_depth_m) if p.measured_depth_m is not None else None,
            rop=float(p.rate_of_penetration_m_hr) if p.rate_of_penetration_m_hr is not None else None,
            wob=float(p.weight_on_bit_kn) if p.weight_on_bit_kn is not None else None,
            rpm=float(p.rotary_rpm) if p.rotary_rpm is not None else None,
            torque=float(p.torque_kn_m) if p.torque_kn_m is not None else None,
            pressure=float(p.standpipe_pressure_kpa) if p.standpipe_pressure_kpa is not None else None,
            mud_flow=float(p.flow_rate_lpm) if p.flow_rate_lpm is not None else None,
            mud_weight=float(p.mud_weight_kg_m3) if p.mud_weight_kg_m3 is not None else None,
            formation=formations[0].formation_name if formations else None,
        )

    def trend(self, well_id: str, limit: int = 120):
        self.get_well(well_id)
        params = list(self.repo.get_drilling_parameters(well_id, limit=limit))
        from ..schemas import TrendPointResponse
        return [TrendPointResponse(
            timestamp=p.recorded_at,
            depth=float(p.measured_depth_m) if p.measured_depth_m is not None else None,
            rop=float(p.rate_of_penetration_m_hr) if p.rate_of_penetration_m_hr is not None else None,
            torque=float(p.torque_kn_m) if p.torque_kn_m is not None else None,
            pressure=float(p.standpipe_pressure_kpa) if p.standpipe_pressure_kpa is not None else None,
        ) for p in params]

    def trajectory(self, well_id, limit, offset):
        well = self.repo.get_well(well_id)
        if well is None:
            raise ResourceNotFound(f"Well '{well_id}' was not found")
        stmt = select(self.WellTrajectory).where(self.WellTrajectory.well_id == well.id).order_by(self.WellTrajectory.sequence_no).offset(offset).limit(limit)
        points = self.session.scalars(stmt).all()
        total = self.session.scalar(select(func.count()).select_from(self.WellTrajectory).where(self.WellTrajectory.well_id == well.id)) or 0
        return [TrajectoryPointResponse.model_validate(x) for x in points], int(total)
